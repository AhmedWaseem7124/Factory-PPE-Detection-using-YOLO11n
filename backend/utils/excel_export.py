def _autofit_columns(ws, min_width=12):
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            if cell.value is not None:
                val_str = str(cell.value)
                max_len = max(max_len, len(val_str))
        ws.column_dimensions[col_letter].width = max(max_len + 4, min_width)


def _add_company_header(ws, title_text, subtitle_text="", end_col=8):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=end_col)
    cell1 = ws.cell(row=1, column=1, value="Crescent Steel & Allied Products Ltd. | Factory PPE Monitoring System")
    cell1.font = Font(name="Calibri", size=10, bold=True, color="94A3B8")
    cell1.fill = FILL_TITLE
    cell1.alignment = ALIGN_LEFT

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=end_col)
    cell2 = ws.cell(row=2, column=1, value=title_text.upper())
    cell2.font = FONT_TITLE
    cell2.fill = FILL_TITLE
    cell2.alignment = ALIGN_LEFT

    ws.merge_cells(start_row=3, start_column=1, end_row=3, end_column=end_col)
    sub_val = f"Generated On: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}  |  {subtitle_text}" if subtitle_text else f"Generated On: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
    cell3 = ws.cell(row=3, column=1, value=sub_val)
    cell3.font = FONT_SUBTITLE
    cell3.fill = FILL_TITLE
    cell3.alignment = ALIGN_LEFT

    ws.row_dimensions[1].height = 20
    ws.row_dimensions[2].height = 28
    ws.row_dimensions[3].height = 20


