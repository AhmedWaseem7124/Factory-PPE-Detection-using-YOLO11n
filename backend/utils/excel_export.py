# 2. INCIDENT INVESTIGATION REPORT
# =========================================================
def generate_incident_investigation_excel(report_data, filters=None, generated_by="HSE Officer"):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Incident Investigation"
    ws.views.sheetView[0].showGridLines = True

    filters = filters or {}
    start_d = filters.get("start_date") or "Beginning"
    end_d = filters.get("end_date") or "Today"
    z_f = filters.get("zone") or "All Zones"
    e_f = filters.get("event_type") or "All Types"
    s_f = filters.get("status") or "All Statuses"

    _add_company_header(
        ws,
        title_text="Incident Investigation Detailed Report",
        subtitle_text=f"Scope: {start_d} to {end_d}  |  Generated By: {generated_by}",
        end_col=10
    )

    # Filter Audit Block (Rows 5 - 6)
    filter_items = [
        ("Date Range", f"{start_d} to {end_d}"),
        ("Zone Filter", z_f),
        ("Violation Category", e_f),
        ("Status Scope", "Resolved Only" if s_f in ["Completed", "Resolved"] else s_f),
        ("Total Incidents", report_data.get("total_matching", len(report_data.get("incidents", [])))),
    ]

    for idx, (flbl, fval) in enumerate(filter_items, start=1):
        fc1 = ws.cell(row=5, column=idx, value=flbl)
        fc1.font = FONT_KPI_LABEL
        fc1.fill = FILL_KPI_CARD
        fc1.alignment = ALIGN_CENTER
        fc1.border = BORDER_CELL

        fc2 = ws.cell(row=6, column=idx, value=fval)
        fc2.font = FONT_BOLD
        fc2.fill = FILL_KPI_CARD
        fc2.alignment = ALIGN_CENTER
        fc2.border = BORDER_CELL

    # Incident Table Headers (Row 8)
    headers = [
        "Incident ID", "Track ID", "Zone", "Violation Type",
        "Start Time", "End Time", "Duration (s)", "Status",
        "Snapshot", "Video Clip"
    ]

    ws.row_dimensions[8].height = 25
    for c_idx, h_text in enumerate(headers, start=1):
        cell = ws.cell(row=8, column=c_idx, value=h_text)
        cell.font = FONT_HEADER
        cell.fill = FILL_HEADER
        cell.alignment = ALIGN_CENTER

    incidents = report_data.get("incidents", [])
    for r_idx, inc in enumerate(incidents, start=9):
        is_resolved = inc.get("resolved") == 1 or inc.get("status") in ["Completed", "Resolved"]
        dur_val = inc.get("duration", 0)
        if is_resolved and dur_val <= 0:
            dur_val = 1

        snap_str = "Available" if inc.get("snapshot_path") else "None"
        vid_str = "Available" if inc.get("video_path") else "None"

        row_vals = [
            inc.get("id"),
            f"#{inc.get('track_id', 'N/A')}",
            inc.get("zone", "Unknown"),
            inc.get("event_type", "Helmet Missing"),
            inc.get("start_time") or inc.get("timestamp"),
            inc.get("end_time") if is_resolved else "Ongoing",
            dur_val,
            "Resolved" if is_resolved else "Active",
            snap_str,
            vid_str
        ]

        fill = FILL_ZEBRA_EVEN if r_idx % 2 == 0 else FILL_ZEBRA_ODD
        for c_idx, val in enumerate(row_vals, start=1):
            cell = ws.cell(row=r_idx, column=c_idx, value=val)
            cell.fill = fill
            cell.font = FONT_REGULAR
            cell.alignment = ALIGN_CENTER
            cell.border = BORDER_CELL

    # AutoFilter & Freeze Panes
    last_row = max(len(incidents) + 8, 9)
    ws.auto_filter.ref = f"A8:J{last_row}"
    ws.freeze_panes = "A9"

    _autofit_columns(ws)
    output = io.BytesIO()
    wb.save(output)
    output.seek(0)
    return output.getvalue()


