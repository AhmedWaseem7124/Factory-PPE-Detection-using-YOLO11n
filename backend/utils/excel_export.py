# 1. DAILY HSE SUMMARY REPORT
# =========================================================
def generate_daily_summary_excel(report_data, generated_by="HSE Officer"):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Daily Summary"
    ws.views.sheetView[0].showGridLines = True

    _add_company_header(
        ws,
        title_text="Daily HSE Summary Report",
        subtitle_text=f"Report Date: {report_data.get('date', 'N/A')} | Generated By: {generated_by}",
        end_col=7
    )

    # KPI Section (Row 5 - 6)
    kpis = [
        ("Total Incidents", report_data.get("todays_incidents", 0)),
        ("Active Violations", report_data.get("active_incidents", 0)),
        ("Resolved Incidents", report_data.get("completed_incidents", 0)),
        ("Workers Monitored", report_data.get("total_workers", 0)),
        ("Compliance Rate", f"{report_data.get('compliance_rate', 0)}%"),
        ("Avg Resolution Time", f"{report_data.get('avg_duration', 0)}s"),
        ("Highest Risk Zone", report_data.get("highest_risk_zone", "None")),
    ]

    for idx, (label, val) in enumerate(kpis, start=1):
        lbl_cell = ws.cell(row=5, column=idx, value=label)
        lbl_cell.font = FONT_KPI_LABEL
        lbl_cell.fill = FILL_KPI_CARD
        lbl_cell.alignment = ALIGN_CENTER
        lbl_cell.border = BORDER_CELL

        val_cell = ws.cell(row=6, column=idx, value=val)
        val_cell.font = FONT_KPI_VAL
        val_cell.fill = FILL_KPI_CARD
        val_cell.alignment = ALIGN_CENTER
        val_cell.border = BORDER_CELL

    # Executive Summary Paragraph (Row 8)
    ws.merge_cells("A8:G8")
    sec_cell = ws.cell(row=8, column=1, value="EXECUTIVE SUMMARY")
    sec_cell.font = FONT_SECTION
    sec_cell.fill = FILL_SECTION
    sec_cell.alignment = ALIGN_LEFT

    ws.merge_cells("A9:G9")
    sum_cell = ws.cell(row=9, column=1, value=report_data.get("executive_summary", "No summary available."))
    sum_cell.font = FONT_REGULAR
    sum_cell.alignment = Alignment(horizontal="left", vertical="center", wrap_text=True)

    # Hourly Distribution & Zone Breakdown (Row 11)
    ws.merge_cells("A11:C11")
    ws.cell(row=11, column=1, value="24-HOUR INCIDENT BREAKDOWN").font = FONT_SECTION
    ws.cell(row=11, column=1).fill = FILL_SECTION

    ws.merge_cells("E11:G11")
    ws.cell(row=11, column=5, value="ZONE SAFETY MATRIX").font = FONT_SECTION
    ws.cell(row=11, column=5).fill = FILL_SECTION

    # Table Headers (Row 12)
    h1 = ws.cell(row=12, column=1, value="Hour")
    h2 = ws.cell(row=12, column=2, value="Incidents Logged")
    for h in [h1, h2]:
        h.font = FONT_HEADER
        h.fill = FILL_HEADER
        h.alignment = ALIGN_CENTER

    z_headers = ["Zone", "Monitored Workers", "Violations Logged"]
    for z_idx, z_h in enumerate(z_headers, start=5):
        cell = ws.cell(row=12, column=z_idx, value=z_h)
        cell.font = FONT_HEADER
        cell.fill = FILL_HEADER
        cell.alignment = ALIGN_CENTER

    # Hourly Data Rows
    hourly_list = report_data.get("hourly_breakdown", [])
    for r_idx, item in enumerate(hourly_list, start=13):
        c1 = ws.cell(row=r_idx, column=1, value=item.get("hour", ""))
        c2 = ws.cell(row=r_idx, column=2, value=item.get("count", 0))
        fill = FILL_ZEBRA_EVEN if r_idx % 2 == 0 else FILL_ZEBRA_ODD
        c1.fill = fill
        c2.fill = fill
        c1.alignment = ALIGN_CENTER
        c2.alignment = ALIGN_CENTER
        c1.border = BORDER_CELL
        c2.border = BORDER_CELL

    # Zone Data Rows
    zone_matrix = report_data.get("zone_matrix", [])
    for zm_idx, zm in enumerate(zone_matrix, start=13):
        zc1 = ws.cell(row=zm_idx, column=5, value=zm.get("zone", "Unknown"))
        zc2 = ws.cell(row=zm_idx, column=6, value=zm.get("total_workers", 0))
        zc3 = ws.cell(row=zm_idx, column=7, value=zm.get("violations", 0))
        fill = FILL_ZEBRA_EVEN if zm_idx % 2 == 0 else FILL_ZEBRA_ODD
        for zc in [zc1, zc2, zc3]:
            zc.fill = fill
            zc.alignment = ALIGN_CENTER
            zc.border = BORDER_CELL
            zc.font = FONT_REGULAR

    # Top Incidents Section (Row 38)
    ws.merge_cells("A38:G38")
    ws.cell(row=38, column=1, value="TOP INCIDENTS LOGGED TODAY").font = FONT_SECTION
    ws.cell(row=38, column=1).fill = FILL_SECTION

    top_cols = ["ID", "Track ID", "Timestamp", "Zone", "Violation Type", "Duration (s)", "Status"]
    for c_idx, col_name in enumerate(top_cols, start=1):
        c = ws.cell(row=39, column=c_idx, value=col_name)
        c.font = FONT_HEADER
        c.fill = FILL_HEADER
        c.alignment = ALIGN_CENTER

    top_incidents = report_data.get("top_incidents", [])
    for t_idx, inc in enumerate(top_incidents, start=40):
        row_cells = [
            ws.cell(row=t_idx, column=1, value=inc.get("id")),
            ws.cell(row=t_idx, column=2, value=f"#{inc.get('track_id', 'N/A')}"),
            ws.cell(row=t_idx, column=3, value=inc.get("timestamp")),
            ws.cell(row=t_idx, column=4, value=inc.get("zone")),
            ws.cell(row=t_idx, column=5, value=inc.get("event_type")),
            ws.cell(row=t_idx, column=6, value=inc.get("duration")),
            ws.cell(row=t_idx, column=7, value="Resolved" if inc.get("status") in ["Completed", "Resolved"] or inc.get("resolved") == 1 else "Active"),
        ]
        fill = FILL_ZEBRA_EVEN if t_idx % 2 == 0 else FILL_ZEBRA_ODD
        for cell in row_cells:
            cell.fill = fill
            cell.alignment = ALIGN_CENTER
            cell.border = BORDER_CELL
            cell.font = FONT_REGULAR

    _autofit_columns(ws)
    output = io.BytesIO()
    wb.save(output)
    output.seek(0)
    return output.getvalue()


